export default function EventDetailPage({ params }: { params: { slug: string } }) {
    const event = allEvents.find(e => e.slug === params.slug);

    if (!event) {
        return (
            <div className="container py-16 md:py-24 text-center">
                <h1 className="font-headline text-4xl font-bold">Acara tidak ditemukan</h1>
                <p className="mt-4 text-muted-foreground">Maaf, kami tidak dapat menemukan acara yang Anda cari.</p>
            </div>
        );
    }
    
    return <EventDetailPageContent event={event} />;
}

export async function generateStaticParams() {
  return allEvents.map(event => ({
    slug: event.slug,
  }));
}
